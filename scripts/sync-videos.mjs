import {readdirSync, readFileSync, writeFileSync, existsSync} from 'node:fs';
import {join, dirname, basename, extname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const videosDir = join(root, 'src', 'videos');

if (!existsSync(videosDir)) {
	console.error('Videos directory not found:', videosDir);
	process.exit(1);
}

const entries = readdirSync(videosDir, {withFileTypes: true});
const videoFiles = [];

for (const entry of entries) {
	// Single file videos: src/videos/<video-name>.tsx (excluding index.tsx, EmptyPlaceholder.tsx)
	if (entry.isFile() && entry.name.endsWith('.tsx')) {
		if (entry.name !== 'index.tsx' && entry.name !== 'EmptyPlaceholder.tsx' && !entry.name.startsWith('test-')) {
			videoFiles.push({
				idName: entry.name.replace(/\.tsx$/, ''),
				importPath: `./${entry.name.replace(/\.tsx$/, '')}`,
			});
		}
	}
	// (Optional fallback) Folder-based videos: src/videos/<folder-name>/index.tsx
	else if (entry.isDirectory() && existsSync(join(videosDir, entry.name, 'index.tsx'))) {
		videoFiles.push({
			idName: entry.name,
			importPath: `./${entry.name}`,
		});
	}
}

console.log(`[CineFlow Sync] Discovered ${videoFiles.length} video composition(s):`, videoFiles.map(v => v.idName));

// Generate clean src/videos/index.tsx
let imports = `import React from 'react';\nimport {Composition, Folder} from 'remotion';\nimport {EmptyPlaceholder} from './EmptyPlaceholder';\n`;
let compTags = '';

videoFiles.forEach((v, idx) => {
	const varName = `Video_${idx}_${v.idName.replace(/[^a-zA-Z0-9]/g, '_')}`;
	imports += `import * as ${varName} from '${v.importPath}';\n`;

	compTags += `
			{/* Auto-registered from ${v.importPath} */}
			{(() => {
				const mod = ${varName} as any;
				const conf = mod.config || mod.CONFIG || Object.values(mod).find(
					(x: any) => x && typeof x === 'object' && 'durationInFrames' in x && 'fps' in x
				) as any;
				const Comp = mod.default || Object.values(mod).find(
					(x) => typeof x === 'function' && x !== mod.default
				) as React.FC;
				if (!conf || !Comp) return null;
				return (
					<Composition
						id={conf.id || '${v.idName}'}
						component={Comp}
						durationInFrames={conf.durationInFrames || 300}
						fps={conf.fps || 30}
						width={conf.width || 1920}
						height={conf.height || 1080}
					/>
				);
			})()}`;
});

const content = `// AUTO-GENERATED BY scripts/sync-videos.mjs
// DO NOT EDIT MANUALLY - To add or remove a video, simply create or delete its file in src/videos/<video-name>.tsx
${imports}
export const VideoCompositions: React.FC = () => {
	return (
		<Folder name="Videos">
			<Composition
				id="Welcome"
				component={EmptyPlaceholder}
				durationInFrames={150}
				fps={30}
				width={1920}
				height={1080}
			/>${compTags}
		</Folder>
	);
};
`;

writeFileSync(join(videosDir, 'index.tsx'), content);
console.log(`[CineFlow Sync] Successfully synced src/videos/index.tsx with 0 manual intervention required!`);
